"""Differential checks against vdf 3.4; no upstream source or fixtures vendored."""
import argparse
import hashlib
import json
import pathlib
import random
import shutil
import struct
import subprocess
import sys

import vdf

ROOT = pathlib.Path(__file__).resolve().parents[1]


def ordered(value):
    return [{"key": k, "value": ordered(v) if isinstance(v, vdf.VDFDict) else v}
            for k, v in value.items()]


def generated(rng, depth):
    result = vdf.VDFDict()
    for _ in range(rng.randrange(1, 7)):
        key = rng.choice(["duplicate", "duplicate", "name", "中文", "space key"])
        result[key] = generated(rng, depth - 1) if depth and rng.randrange(3) == 0 else rng.choice([
            "", "plain", "中文😀", 'a "quote"', "a\\path", "line\nbreak", "tab\there", "{} // data"])
    return result


def binary_vectors():
    vectors = []
    sources = []
    for seed in range(24):
        doc = vdf.VDFDict()
        model = []

        def add(key, value, moon):
            doc[key] = value
            model.append('{ key: ' + json.dumps(key, ensure_ascii=False) + ', value: @moonvalve.' + moon + ' }')

        add("dup", "中文😀" + str(seed), 'StringValue(' + json.dumps("中文😀" + str(seed), ensure_ascii=False) + ')')
        add("dup", seed - 2147483648, f'Int32Value({seed - 2147483648})')
        value = -0.0 if seed == 0 else seed / 8
        bits = struct.unpack('<I', struct.pack('<f', value))[0]
        add("float", value, f'Float32Bits({bits}U)')
        add("pointer", vdf.POINTER(-1 - seed), f'Pointer32({(0xffffffff - seed)}U)')
        add("color", vdf.COLOR(0x04030201 + seed), f'Color32({0x04030201 + seed}U)')
        add("u64", vdf.UINT_64(18446744073709551615 - seed), f'UInt64Value({18446744073709551615 - seed}UL)')
        add("i64", vdf.INT_64(-9223372036854775808 + seed), f'Int64Value({-9223372036854775808 + seed}L)')
        nested = vdf.VDFDict()
        nested['empty'] = vdf.VDFDict()
        nested['text'] = '\ufeffvalue'
        add("object", nested, 'ObjectValue([{key: "empty", value: @moonvalve.ObjectValue([])}, {key: "text", value: @moonvalve.StringValue("\\uFEFFvalue")}])')
        encoded = vdf.binary_dumps(doc)
        assert ordered(vdf.binary_loads(encoded, mapper=vdf.VDFDict, merge_duplicate_keys=False)) == ordered(doc)
        vectors.append({"seed": seed, "hex": encoded.hex()})
        literal = 'b"' + ''.join('\\x%02x' % b for b in encoded) + '"'
        sources.append('///|\ntest "vdf 3.4 binary reference vector %d" {\n  let expected : Array[@moonvalve.BinaryEntry] = [\n    %s\n  ]\n  let bytes = %s\n  assert_eq(@moonvalve.encode_binary(expected), bytes)\n  assert_eq(@moonvalve.decode_binary(bytes), expected)\n}\n' % (seed, ',\n    '.join(model), literal))
    return vectors, '\n'.join(sources)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--refresh', action='store_true', help='regenerate synthetic binary fixtures')
    parser.add_argument('--native', action='store_true')
    parser.add_argument('--cases', type=int, default=80)
    args = parser.parse_args()
    if vdf.__version__ != '3.4':
        raise RuntimeError('Install the pinned reference: python -m pip install vdf==3.4')
    vectors, source = binary_vectors()
    fixture = ROOT / 'fixtures/reference-binary.json'
    test = ROOT / 'reference_binary_test.mbt'
    digest = hashlib.sha256(json.dumps(vectors, sort_keys=True).encode()).hexdigest()
    marker = '// vectors-sha256: ' + digest
    if args.refresh:
        fixture.write_text(json.dumps(vectors, indent=2) + '\n', encoding='utf-8')
        test.write_text('// Synthetic vectors generated by scripts/check-reference.py using vdf==3.4.\n' + marker + '\n' + source, encoding='utf-8')
    else:
        assert json.loads(fixture.read_text(encoding='utf-8')) == vectors, 'Reference fixture differs; inspect before refreshing'
        actual = test.read_text(encoding='utf-8')
        assert marker in actual
        for vector in vectors:
            literal = 'b"' + ''.join('\\x%02x' % b for b in bytes.fromhex(vector['hex'])) + '"'
            assert literal in actual, 'Missing binary vector in MoonBit tests'
    if args.cases < 0 or args.cases > 2000:
        raise ValueError('cases must be 0..2000')
    executable = ROOT / ('_build/native/release/build/cmd/main/main' + ('.exe' if sys.platform == 'win32' else '') if args.native else '_build/js/release/build/cmd/main/main.js')
    command = [str(executable)] if args.native else [shutil.which('node') or 'node', str(executable)]

    def cli(action, text):
        result = subprocess.run(command + [action, '-'], input=text, encoding='utf-8', capture_output=True, check=False, timeout=15)
        if result.returncode:
            raise AssertionError(result.stderr)
        return result.stdout

    rng = random.Random(20261023)
    for case in range(args.cases):
        doc = generated(rng, 3)
        text = vdf.dumps(doc, pretty=True, escaped=True)
        expected = ordered(doc)
        assert json.loads(cli('parse', text)) == expected, f'Reference -> MoonValve case {case}'
        written = cli('from-json', json.dumps(expected, ensure_ascii=False))
        actual = vdf.loads(written, mapper=vdf.VDFDict, merge_duplicate_keys=False, escaped=True)
        assert ordered(actual) == expected, f'MoonValve -> reference case {case}'
    print(f'{len(vectors)} binary reference vectors verified; {args.cases} text documents checked in both directions')


if __name__ == '__main__':
    main()
